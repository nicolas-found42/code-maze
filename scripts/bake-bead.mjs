// Boolean modeling happens at authoring time, never for every file or frame.
import { writeFile } from "node:fs/promises";
import { CylinderGeometry, MeshStandardMaterial } from "three";
import { RoundedBoxGeometry } from "three/examples/jsm/geometries/RoundedBoxGeometry.js";
import { Brush, Evaluator, SUBTRACTION } from "three-bvh-csg";

const paint = new MeshStandardMaterial();
const timber = new MeshStandardMaterial();
const block = new Brush(new RoundedBoxGeometry(30, 32, 30, 4, 4), paint);
const drill = new Brush(new CylinderGeometry(7, 7, 44, 64), timber);
block.updateMatrixWorld();
drill.updateMatrixWorld();
const evaluator = new Evaluator();
const result = evaluator.evaluate(block, drill, SUBTRACTION);
const geometry = result.geometry;
// Compact, engine-independent vertex data. The browser shares its one local Three.
const attributes = Object.fromEntries(["position", "normal", "uv"].map((name) => [name,
  Array.from(geometry.getAttribute(name).array, (value) => Number(value.toFixed(5))),
]));
const index = geometry.index ? Array.from(geometry.index.array) : Array.from({ length: geometry.getAttribute("position").count }, (_, i) => i);
const data = { attributes, index, groups: geometry.groups };
await writeFile(new URL("../docs/vendor/bead-block.js", import.meta.url),
  `// Generated by npm run assets:3d (three-bvh-csg). Do not hand edit.\nexport default ${JSON.stringify(data)};\n`);
console.log(`Baked drilled rounded block: ${index.length / 3} triangles`);
